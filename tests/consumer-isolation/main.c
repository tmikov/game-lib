/* A 1x1 red PNG, the smallest thing that exercises the decoder. */
#include <stb/stb_image.h>
#include <stdio.h>

static const unsigned char kPng[] = {
  0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,0x00,0x00,0x00,0x0d,0x49,0x48,0x44,0x52,
  0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x01,0x08,0x02,0x00,0x00,0x00,0x90,0x77,0x53,
  0xde,0x00,0x00,0x00,0x0c,0x49,0x44,0x41,0x54,0x08,0xd7,0x63,0xf8,0xcf,0xc0,0x00,
  0x00,0x03,0x01,0x01,0x00,0x18,0xdd,0x8d,0xb0,0x00,0x00,0x00,0x00,0x49,0x45,0x4e,
  0x44,0xae,0x42,0x60,0x82
};

int main(void) {
  int w = 0, h = 0, comp = 0;
  unsigned char *px = stbi_load_from_memory(kPng, (int)sizeof kPng, &w, &h, &comp, 3);
  if (!px) { fprintf(stderr, "decode failed: %s\n", stbi_failure_reason()); return 1; }
  if (w != 1 || h != 1) { fprintf(stderr, "got %dx%d\n", w, h); return 1; }
  if (px[0] != 255 || px[1] != 0 || px[2] != 0) {
    fprintf(stderr, "got rgb %d,%d,%d\n", px[0], px[1], px[2]); return 1;
  }
  stbi_image_free(px);
  return 0;
}
